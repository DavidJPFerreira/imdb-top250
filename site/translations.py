def translate_genres_str(genres_str, lang="pt"):
    if not genres_str:
        return ""
    if lang == "en":
        return genres_str
    mapping = GENRE_MAP.get(lang, {})
    parts = [g.strip() for g in genres_str.split(",") if g.strip()]
    return ", ".join(mapping.get(p, p) for p in parts)


